import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const root = 'public/compiler';
const assets = [];
async function visit(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await visit(path);
    else if (entry.name !== 'assets.sha256.json') {
      const bytes = await readFile(path);
      assets.push({
        path: path.replaceAll('\\', '/').replace('public/', '/'),
        size: bytes.length,
        sha256: createHash('sha256').update(bytes).digest('hex'),
      });
    }
  }
}
await visit(root);
assets.sort((a, b) => a.path.localeCompare(b.path));
const manifest = `${JSON.stringify({ assets }, null, 2)}\n`;
await writeFile(join(root, 'assets.sha256.json'), manifest);
// Every compiler worker, script, WASM and package request carries this content version, so those URLs
// can be cached immutably and any asset change yields new cache keys for the whole engine.
const version = compilerVersion(assets);
await writeFile('src/compiler-version.js', `// Generated by scripts/asset-hashes.mjs from public/compiler/assets.sha256.json.\nexport const COMPILER_VERSION = '${version}';\n`);
console.log(`Recorded SHA-256 for ${assets.length} distributed compiler assets (version ${version}).`);

function compilerVersion(list) {
  return createHash('sha256').update(list.map(asset => `${asset.path}\0${asset.sha256}`).join('\n')).digest('hex').slice(0, 16);
}
